package main

import (
	"context"
	"errors"
	"fmt"
	"log"
	"os"
	"os/signal"
	"strings"
	"sync"
	"syscall"
	"time"

	rmq "github.com/rabbitmq/rabbitmq-amqp-go-client/pkg/rabbitmqamqp"
)

const brokerURI = "amqp://guest:guest@localhost:5672/"
const xchange = "logs"

func releaseResource(fn func(ctx context.Context) error) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	if err := fn(ctx); err != nil {
		fmt.Println(err)
	}
}

func spawn(ctx context.Context, keys []string) {
	env := rmq.NewEnvironment(brokerURI, nil)

	conn, err := env.NewConnection(ctx)
	if err != nil {
		panic(err)
	}
	defer releaseResource(env.CloseConnections)

	_, err = conn.Management().DeclareExchange(ctx, &rmq.TopicExchangeSpecification{Name: xchange})
	if err != nil {
		panic(err)
	}

	qInfo, err := conn.Management().DeclareQueue(ctx, &rmq.AutoGeneratedQueueSpecification{
		IsExclusive:  true,
		IsAutoDelete: true,
	})
	if err != nil {
		panic(err)
	}

	for _, key := range keys {
		_, err = conn.Management().Bind(ctx, &rmq.ExchangeToQueueBindingSpecification{
			SourceExchange:   "logs",
			DestinationQueue: qInfo.Name(),
			BindingKey:       key,
		})
		if err != nil {
			panic(err)
		}
	}

	label := strings.Join(keys, "/")

	log.Printf(" [%s] subscribed", label)

	consumer, err := conn.NewConsumer(ctx, qInfo.Name(), nil)
	if err != nil {
		panic(err)
	}

	for {
		delivery, err := consumer.Receive(ctx)
		if err != nil {
			if errors.Is(err, context.Canceled) {
				break
			}
			panic(err)
		}

		msg := delivery.Message()

		var payload []byte
		if len(msg.Data) > 0 {
			payload = msg.Data[0]
		}

		log.Printf("[%s] %s", label, payload)

		err = delivery.Accept(ctx)
		if err != nil {
			panic(err)
		}
	}
	log.Printf(" [%s] shutting down", label)
}

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	var wg sync.WaitGroup

	for _, key := range [][]string{{"kern.*"}, {"*.error"}, {"kern.error", "auth.warn"}} {
		wg.Go(func() {
			spawn(ctx, key)
		})
	}

	wg.Wait()
}
